def add_delisting_returns(panel):
    """
    02b_상폐수익률.py 결과로 상폐한 달(반영연월) 줄을 추가하고, 상폐 수익률을 반영한 수익률 열을 만든다.
    기존 수익률 열은 그대로 둔다. 백테스트에는 '수정주가수익률_배당포함_상폐반영_%'를 쓴다.
    """
    d = pd.read_parquet(OUT / "상폐수익률.parquet")[["종목코드", "반영연월", "상폐수익률_%"]]
    d = d.rename(columns={"반영연월": "연월"})
    panel = panel.merge(d, on=["연월", "종목코드"], how="outer")
    base = "수정주가수익률_배당포함_%"
    # 반영연월에 이미 수익률이 있으면(있어선 안 됨) 기존 값을 우선한다
    panel["수정주가수익률_배당포함_상폐반영_%"] = panel[base].fillna(panel["상폐수익률_%"])
    panel["상폐월"] = panel["상폐수익률_%"].notna()
    panel = panel.drop(columns="상폐수익률_%")
    설명.extend([
        ("월별패널", "수정주가수익률_배당포함_상폐반영_%", "", "03 + 40~43(02b)", "%",
         "배당포함 수익률 + 상폐한 달의 상폐수익률(마지막 달 말 → 정리매매 마지막 날). 백테스트 기본"),
        ("월별패널", "상폐월", "", "02b", "참/거짓", "상폐수익률을 넣은 줄이면 참(다른 열은 대부분 빈칸)"),
    ])
    return panel


def build_panel():
    names = {}
    parts = []
    for stem, mapping in PANEL_SOURCES.items():
        df = load(stem)
        names.update(dict(zip(df["종목코드"], df["종목명"])))
        df = df.set_index(["연월", "종목코드"])[list(mapping)]
        parts.append(df.rename(columns={k: v[0] for k, v in mapping.items()}))
        note("월별패널", stem, mapping)
    panel = pd.concat(parts, axis=1, join="outer")

    value_cols = [c for c in panel.columns if c not in ALWAYS_FILLED]
    panel = panel[panel[value_cols].notna().any(axis=1)].reset_index()
    panel = add_delisting_returns(panel)

    listing = load("29_상장일_상폐일")
    names.update(dict(zip(listing["종목코드"], listing["종목명"])))
    listing = listing[["종목코드", *LISTING]].rename(columns={k: v[0] for k, v in LISTING.items()})
    note("월별패널", "29_상장일_상폐일", LISTING)
    panel = panel.merge(listing, on="종목코드", how="left")
    panel.insert(2, "종목명", panel["종목코드"].map(names))
    설명[:0] = [("월별패널", "연월", "", "", "YYYY-MM", "월말 기준 연월. 파일마다 말일이 달라 연월로 맞춤"),
               ("월별패널", "종목코드", "", "", "", "A + 6자리. 예: A005930"),
               ("월별패널", "종목명", "", "", "", "현재 종목명")]
    return panel.sort_values(["종목코드", "연월"]).reset_index(drop=True)


