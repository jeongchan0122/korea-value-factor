    e = pd.concat([load(f) for f in EARNINGS_FILES], ignore_index=True)
    e = e[["종목코드", "종목명", "결산월", "회계연도", "분기", *EARNINGS]].rename(
        columns={k: v[0] for k, v in EARNINGS.items()} | {"결산월": "결산월_현재"})
    p = pd.concat([load(f) for f in PRELIM_FILES], ignore_index=True)[keys + ["종목명", "결산월", "잠정치발표일"]]
    q = e.merge(p, on=keys, how="outer", suffixes=("", "_잠정"))
    # 잠정치 파일에만 있는 줄은 그 파일의 종목명·결산월로 채움
