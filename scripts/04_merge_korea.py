def load(stem):
    return pd.read_parquet(TIDY / f"{stem}.parquet")


def note(table, src, mapping):
    """mapping: {원래이름: (새이름, 단위, 설명)} 을 설명표에 기록."""
    for orig, (new, unit, desc) in mapping.items():
        설명.append((table, new, orig, src, unit, desc))


def fiscal_end_index(year, fye_month):
    """회계연도 마지막 달을 '연*12 + (월-1)' 정수로. 결산월이 1~5월이면 다음 해에 끝난다(Compustat과 같은 규칙)."""
    end_year = np.where(fye_month <= 5, year + 1, year)
    return end_year * 12 + (fye_month - 1)


def index_to_ym(idx):
    idx = pd.Series(idx)
    return (idx // 12).astype("Int64").astype(str) + "-" + (idx % 12 + 1).astype("Int64").astype(str).str.zfill(2)


def yyyymmdd_to_date(s):
    return pd.to_datetime(s.astype("Int64").astype("string"), format="%Y%m%d", errors="coerce")


