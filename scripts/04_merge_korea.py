    desc = pd.DataFrame(설명, columns=["표", "열이름", "원래이름", "출처파일", "단위", "설명"])
    order = {n: i for i, n in enumerate(results)}
    desc = desc.sort_values("표", key=lambda s: s.map(order), kind="stable")
    desc.to_csv(OUT / "열이름설명.csv", index=False, encoding="utf-8-sig")  # 엑셀에서 한글 안 깨지게
    # 설명표에 빠진 열이 없는지 확인
    for name, df in results.items():
        missing = set(df.columns) - set(desc.loc[desc["표"] == name, "열이름"])
        if missing:
            print(f"  [주의] {name} 설명 없는 열: {sorted(missing)}")
    print(f"열이름설명.csv   {len(desc)}행")


